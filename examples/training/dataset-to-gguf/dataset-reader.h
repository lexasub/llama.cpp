#pragma once

#include <string>
#include <vector>
#include <cstdint>
#include "llama.h" // Для llama_token

// Абстрактный базовый класс для чтения данных.
// Определяет интерфейс, который должны реализовать все конкретные ридеры.
class DatasetReader {
public:
    // Виртуальный деструктор для корректного удаления производных классов.
    virtual ~DatasetReader() = default;

    // Метод для открытия источника данных.
    // path: путь к файлу или другой идентификатор источника данных.
    // Возвращает true, если источник успешно открыт, иначе false.
    virtual bool open(const std::string& path) = 0;

    // Метод для чтения следующей последовательности токенов.
    // tokens: вектор, в который будут записаны прочитанные токены.
    // Возвращает true, если последовательность успешно прочитана, иначе false (включая конец файла).
    virtual bool read_next_sequence(std::vector<llama_token>& tokens) = 0;

    // Метод для закрытия источника данных.
    virtual void close() = 0;

    // Метод для сброса чтения к началу источника данных.
    // Используется для второго прохода по данным.
    virtual bool reset() = 0;
};

